#!/usr/bin/env python3
"""The required-check proposal for `main`, derived from the real workflows (SH-001).

A passing pull request is only as strong as the contexts branch protection
requires. On 2026-10-13 that was `test` alone, while the validator tests,
the corpus check, the journeys and the render ratchet ran beside it and
could fail without blocking anything. Writing a longer list by hand would
repeat the defect this repository keeps finding — a hand-maintained list
that drifts from what it describes — and a required context has failure
modes a list does not show:

  - A context that never reports (a path-filtered workflow, a job skipped
    by `if:` or by PR activity `types`) leaves a required check *pending
    forever* and blocks every pull request it did not run on.
  - A job skipped because a job it `needs` failed reports *skipped*, which
    branch protection counts as success. Requiring it proves nothing unless
    the job it needs is required too.
  - Two jobs with one check name satisfy one rule; requiring the name
    requires neither in particular.
  - `continue-on-error` marks a job advisory by design.

So `conformance/required-checks.json` classifies every job a pull request
can start — `required`, `pending` (should be required, blocked by a named
issue) or `optional` with a reason — and this script checks that
classification against the workflows themselves:

  R1  Every job in a workflow triggered by `pull_request` is classified
      exactly once, and every classification names a job that exists.
  R2  A required or pending job reports on every pull request: no path
      filter, no `types` that omit ordinary pushes, no conditional `if:`,
      no `continue-on-error`, no reusable-workflow indirection, and every
      job it needs is required (or, for a pending job, required or
      pending).
  R3  The check names of required and pending jobs are unique among all
      pull-request jobs, and derivable (matrix values expanded).
  R4  Every lane conformance/lanes.json says runs on every revision is
      required: a lane whose failure does not block a merge does not run
      on every merged revision in any useful sense.
  R5  Optional and pending rows give a reason; pending rows name an issue.

It changes no settings. Applying the list is a repository-administrator
decision; `--payload` prints the body for
`PATCH /repos/{owner}/{repo}/branches/main/protection/required_status_checks`
and `--compare FILE` diffs the proposal against the output of
`gh api repos/{owner}/{repo}/branches/main/protection`.

Usage:
  python3 conformance/required_checks.py                 # R1-R5
  python3 conformance/required_checks.py --markdown      # the table ci-gates.md embeds
  python3 conformance/required_checks.py --payload       # JSON for the settings API
  python3 conformance/required_checks.py --compare protection.json
"""

import argparse
import itertools
import json
import re
import sys
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
WORKFLOWS = REPO_ROOT / ".github" / "workflows"
POLICY = REPO_ROOT / "conformance" / "required-checks.json"
LANES = REPO_ROOT / "conformance" / "lanes.json"
POLICIES = ("required", "pending", "optional")
# The pull-request activity a job has to run on to report for every push
# to a pull request's branch.
ORDINARY_PR_TYPES = {"opened", "synchronize", "reopened"}
# `if:` expressions that do not stop a job from running on a pull request.
UNCONDITIONAL_IFS = {"always()", "!cancelled()", "success() || failure()"}
MATRIX_EXPR = re.compile(r"\$\{\{\s*matrix\.([\w-]+)\s*\}\}")
ANY_EXPR = re.compile(r"\$\{\{.*?\}\}")
BEGIN_MARK = "<!-- required-checks:begin (generated by conformance/required_checks.py --markdown) -->"
END_MARK = "<!-- required-checks:end -->"


def load_workflows(directory: Path = WORKFLOWS) -> dict:
    """{".github/workflows/x.yml": parsed workflow} for every workflow file."""
    found = {}
    for path in sorted(list(directory.glob("*.yml")) + list(directory.glob("*.yaml"))):
        with open(path, encoding="utf-8") as handle:
            found[f".github/workflows/{path.name}"] = yaml.safe_load(handle)
    if not found:
        raise AssertionError(f"no workflows under {directory}, so there is nothing to check")
    return found


def triggers(workflow: dict) -> dict:
    """The `on:` block as a dict. PyYAML reads a bare `on` key as True."""
    on = workflow.get("on", workflow.get(True))
    if isinstance(on, str):
        return {on: None}
    if isinstance(on, list):
        return {event: None for event in on}
    return on or {}


def pull_request_gaps(workflow: dict) -> list | None:
    """Why this workflow might not start on a pull request into main.

    None if pull requests do not start it at all; [] if every push to every
    pull request into main starts it.
    """
    on = triggers(workflow)
    if "pull_request" not in on:
        return None
    config = on["pull_request"] or {}
    gaps = []
    for key in ("paths", "paths-ignore"):
        if config.get(key):
            gaps.append(f"path-filtered ({key}): never reports on a pull request that "
                        "changes none of those paths")
    branches = config.get("branches")
    if branches and "main" not in branches and "**" not in branches and "*" not in branches:
        gaps.append(f"runs only on pull requests into {branches}")
    if "main" in (config.get("branches-ignore") or []):
        gaps.append("ignores pull requests into main")
    types = config.get("types")
    if types and not ORDINARY_PR_TYPES <= set(types):
        missing = sorted(ORDINARY_PR_TYPES - set(types))
        gaps.append(f"pull_request types omit {missing}: does not report on every push")
    return gaps


def _if_is_unconditional(expr) -> bool:
    if expr is None:
        return True
    text = str(expr).strip()
    if text.startswith("${{") and text.endswith("}}"):
        text = text[3:-2].strip()
    return text in UNCONDITIONAL_IFS


def check_names(job_id: str, job: dict) -> tuple:
    """(names, problem): the check-run names GitHub gives this job.

    A job is reported under its `name`, or its id; a matrix job once per
    combination, with `${{ matrix.x }}` substituted in the name or, when
    the name does not use the matrix, the values appended in parentheses.
    """
    name = str(job.get("name") or job_id)
    matrix = (job.get("strategy") or {}).get("matrix")
    if not matrix:
        if ANY_EXPR.search(name):
            return [], f"name {name!r} is an expression that cannot be resolved statically"
        return [name], None
    if isinstance(matrix, str):
        return [], f"matrix {matrix!r} is computed at run time"
    axes = {k: v for k, v in matrix.items() if k not in ("include", "exclude")}
    for key, values in axes.items():
        if not isinstance(values, list):
            return [], f"matrix axis {key!r} is computed at run time"
    include = matrix.get("include") or []
    if axes and include:
        return [], "matrix mixes axes with include; its combinations are not derived here"
    if axes:
        keys = list(axes)
        combos = [dict(zip(keys, values)) for values in itertools.product(*axes.values())]
        for exclusion in matrix.get("exclude") or []:
            combos = [c for c in combos
                      if not all(c.get(k) == v for k, v in exclusion.items())]
    else:
        combos = [dict(entry) for entry in include]
    names = []
    for combo in combos:
        if MATRIX_EXPR.search(name):
            unknown = [k for k in MATRIX_EXPR.findall(name) if k not in combo]
            if unknown:
                return [], f"name uses matrix values {unknown} the matrix does not define"
            resolved = MATRIX_EXPR.sub(lambda m: str(combo[m.group(1)]), name)
        else:
            resolved = f"{name} ({', '.join(str(v) for v in combo.values())})"
        if ANY_EXPR.search(resolved):
            return [], f"name {name!r} uses an expression that cannot be resolved statically"
        names.append(resolved)
    return names, None


def inventory(workflows: dict) -> list:
    """Every job a pull request into main can start, with what could stop it reporting."""
    jobs = []
    for path, workflow in workflows.items():
        workflow_gaps = pull_request_gaps(workflow)
        if workflow_gaps is None:
            continue
        for job_id, job in (workflow.get("jobs") or {}).items():
            gaps = list(workflow_gaps)
            if not _if_is_unconditional(job.get("if")):
                gaps.append(f"conditional (if: {str(job.get('if')).strip()}): a skipped job "
                            "reports success")
            if job.get("continue-on-error"):
                gaps.append("continue-on-error: advisory by design")
            if job.get("uses"):
                gaps.append("calls a reusable workflow: its check names are the callee's")
            names, problem = check_names(job_id, job)
            if problem:
                gaps.append(problem)
            needs = job.get("needs") or []
            jobs.append({
                "workflow": path,
                "job": job_id,
                "names": names,
                "needs": [needs] if isinstance(needs, str) else list(needs),
                "gaps": gaps,
            })
    return jobs


def check_policy(policy: dict, jobs: list, lanes: dict | None) -> list:
    """R1-R5."""
    errors = []
    rows = policy.get("jobs", [])
    by_key = {}
    for row in rows:
        key = (row.get("workflow"), row.get("job"))
        if key in by_key:
            errors.append(f"{key[0]} {key[1]}: classified twice")
        by_key[key] = row
        decision = row.get("policy")
        if decision not in POLICIES:
            errors.append(f"{key[0]} {key[1]}: unknown policy {decision!r} "
                          f"(expected one of {list(POLICIES)})")
        if decision in ("optional", "pending") and not str(row.get("reason", "")).strip():
            errors.append(f"{key[0]} {key[1]}: {decision} without a reason")
        if decision == "pending" and not isinstance(row.get("issue"), int):
            errors.append(f"{key[0]} {key[1]}: pending without the issue that blocks it")

    known = {(job["workflow"], job["job"]): job for job in jobs}
    for key, job in known.items():
        if key not in by_key:
            errors.append(f"{key[0]} {key[1]}: a pull request starts this job but "
                          "conformance/required-checks.json does not classify it")
    for key in by_key:
        if key not in known:
            errors.append(f"{key[0]} {key[1]}: classified, but no pull-request job has that "
                          "name — renamed, removed, or no longer triggered by pull requests")

    names_seen = {}
    for job in jobs:
        for name in job["names"]:
            names_seen.setdefault(name, []).append(f"{job['workflow']} {job['job']}")
    required = []
    for key, job in known.items():
        row = by_key.get(key)
        if not row or row.get("policy") not in ("required", "pending"):
            continue
        decision = row["policy"]
        label = f"{key[0]} {key[1]}"
        for gap in job["gaps"]:
            errors.append(f"{label}: {decision}, but {gap}")
        if not job["names"]:
            errors.append(f"{label}: {decision}, but its check names cannot be derived")
        allowed = ("required",) if decision == "required" else ("required", "pending")
        for need in job["needs"]:
            upstream = by_key.get((key[0], need), {}).get("policy")
            if upstream not in allowed:
                errors.append(
                    f"{label}: {decision}, but it needs {need!r}, which is {upstream or 'unclassified'} "
                    "— if that job fails this one is skipped, and a skipped check counts as passing"
                )
        for name in job["names"]:
            if len(names_seen[name]) > 1:
                errors.append(
                    f"{label}: check name {name!r} is also reported by "
                    f"{[o for o in names_seen[name] if o != label]} — one rule would accept either"
                )
        if decision == "required":
            required += job["names"]
    if not required:
        errors.append("nothing is required, so a pull request that fails every check merges")

    for lane in (lanes or {}).get("lanes", []):
        if lane.get("runs_on_every_revision") is not True:
            continue
        key = (lane.get("workflow"), lane.get("job"))
        decision = by_key.get(key, {}).get("policy")
        if decision != "required":
            errors.append(
                f"lane {lane.get('job')!r} ({lane.get('workflow')}) is declared to run on every "
                f"revision, but its job is {decision or 'unclassified'} — a lane whose failure "
                "does not block a merge certifies nothing about the merged revision"
            )
    return errors


def proposal(policy: dict, jobs: list) -> list:
    """[(name, workflow, job, policy, reason, issue)] in a stable order."""
    by_key = {(row["workflow"], row["job"]): row for row in policy.get("jobs", [])}
    out = []
    for job in jobs:
        row = by_key.get((job["workflow"], job["job"]), {})
        names = job["names"] or [f"{job['job']} (name not derivable)"]
        for name in names:
            out.append((name, job["workflow"], job["job"], row.get("policy", "unclassified"),
                        str(row.get("reason", "")).strip(), row.get("issue")))
    order = {p: i for i, p in enumerate(POLICIES)}
    return sorted(out, key=lambda r: (order.get(r[3], len(order)), r[1], r[0]))


def required_contexts(policy: dict, jobs: list) -> list:
    return [name for name, _, _, decision, _, _ in proposal(policy, jobs)
            if decision == "required"]


def render_markdown(policy: dict, jobs: list) -> str:
    lines = [BEGIN_MARK, "", "| Check name | Workflow → job | Policy | Why |", "|---|---|---|---|"]
    for name, workflow, job, decision, reason, issue in proposal(policy, jobs):
        why = reason or "Reports on every pull request; a failure blocks the merge."
        if issue:
            why = f"#{issue}: {why}"
        lines.append(f"| `{name}` | `{Path(workflow).name}` → `{job}` | {decision} | {why} |")
    lines += ["", END_MARK]
    return "\n".join(lines)


def payload(policy: dict, jobs: list) -> dict:
    app_id = policy.get("app_id")
    return {
        "strict": bool(policy.get("strict", False)),
        "checks": [{"context": name, "app_id": app_id} for name in required_contexts(policy, jobs)],
    }


def compare(protection: dict, policy: dict, jobs: list) -> list:
    """Differences between the proposal and a branch-protection API response."""
    status = protection.get("required_status_checks") or {}
    configured = {c.get("context"): c.get("app_id") for c in status.get("checks") or []}
    for context in status.get("contexts") or []:
        configured.setdefault(context, None)
    wanted = required_contexts(policy, jobs)
    differences = []
    for name in wanted:
        if name not in configured:
            differences.append(f"proposed but not required: {name!r}")
        elif configured[name] != policy.get("app_id"):
            differences.append(f"{name!r} is required from app {configured[name]!r}, "
                               f"not GitHub Actions ({policy.get('app_id')})")
    for name in configured:
        if name not in wanted:
            differences.append(f"required but not proposed: {name!r}")
    return differences


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--policy", type=Path, default=POLICY)
    parser.add_argument("--workflows", type=Path, default=WORKFLOWS)
    parser.add_argument("--lanes", type=Path, default=LANES)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--markdown", action="store_true", help="print the generated table")
    mode.add_argument("--payload", action="store_true",
                      help="print the required_status_checks body an administrator would PUT")
    mode.add_argument("--compare", type=Path, metavar="PROTECTION_JSON",
                      help="diff the proposal against `gh api .../branches/main/protection`")
    args = parser.parse_args(argv)

    policy = json.loads(args.policy.read_text())
    lanes = json.loads(args.lanes.read_text())
    jobs = inventory(load_workflows(args.workflows))
    errors = check_policy(policy, jobs, lanes)
    if errors:
        print("REQUIRED-CHECK PROPOSAL INVALID")
        for e in errors:
            print(f"  - {e}")
        return 1
    if args.markdown:
        print(render_markdown(policy, jobs))
        return 0
    if args.payload:
        print(json.dumps(payload(policy, jobs), indent=2))
        return 0
    if args.compare:
        differences = compare(json.loads(args.compare.read_text()), policy, jobs)
        if differences:
            print("BRANCH PROTECTION DIFFERS FROM THE PROPOSAL")
            for d in differences:
                print(f"  - {d}")
            return 1
        print("BRANCH PROTECTION MATCHES THE PROPOSAL")
        return 0
    required = required_contexts(policy, jobs)
    print(f"REQUIRED-CHECK PROPOSAL OK: {len(required)} required of "
          f"{sum(len(j['names']) or 1 for j in jobs)} pull-request checks in {len(jobs)} jobs")
    return 0


if __name__ == "__main__":
    sys.exit(main())
